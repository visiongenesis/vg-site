(function (R) {
  'use strict';
  var by = {};
  R.camps.forEach(function (c) { by[c.code] = c; });
  R.byCode = by;
  R.money = function (n) { return '$' + n.toLocaleString('en-US'); };
  R.link = function (code, h) { var c = by[code]; return R.MAIN_FORM + (h === 'c' ? c.qC : c.qR); };
  R.esc = function (s) { return s.replace(/&/g, '&amp;'); };
  /* same markup as gen_register.py btn() */
  R.btn = function (code, h) {
    var c = by[code];
    return '<a class="btn reg-btn" data-reg="' + code + '" data-h="' + h + '" href="' + R.esc(R.link(code, h)) + '">Register — ' +
      (h === 'c' ? 'Commuter ' + R.money(c.com) : 'Resident ' + R.money(c.res)) + '</a>';
  };
  function sync() {
    document.querySelectorAll('a[data-reg]').forEach(function (a) {
      var c = by[a.getAttribute('data-reg')];
      if (c) a.setAttribute('href', R.link(c.code, a.getAttribute('data-h')));
    });
  }
  function store(e) {
    var a = e.target && e.target.closest ? e.target.closest('a[data-reg]') : null;
    if (!a) return;
    var c = by[a.getAttribute('data-reg')];
    if (!c) return;
    var h = a.getAttribute('data-h');
    try { localStorage.setItem(R.STORE_KEY, JSON.stringify({ fu: h === 'c' ? c.fuC : c.fuR, camp: c.code, h: h, t: Date.now() })); } catch (err) { /* storage blocked: thanks page falls back to no code */ }
  }
  document.addEventListener('click', store, true);
  document.addEventListener('auxclick', store, true);
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', sync); else sync();
})(window.KC_REG);
